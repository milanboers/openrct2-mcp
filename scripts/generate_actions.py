"""Generate reviewed action bindings. Never import or expose the entire game API."""

import argparse
import json
import keyword
import re
import subprocess
import sys
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / 'src/openrct2_mcp'
START = '    // BEGIN GENERATED ACTION REGISTRY\n'
END = '    // END GENERATED ACTION REGISTRY\n'
HEADER = '# Generated by scripts/generate_actions.py from actions.json. Do not edit.\n'


class Definition(BaseModel):
    model_config = ConfigDict(extra='forbid', strict=True)


class Argument(Definition):
    name: str
    wire_name: str
    type: Literal['integer', 'string', 'boolean']
    action_field: str
    minimum: int | None = None
    maximum: int | None = None
    min_length: int | None = None
    values: dict[str, int | str] | None = None
    multiple_of: int | None = Field(default=None, ge=1)
    boolean_as_integer: bool = False


class Observation(Definition):
    name: str
    property: str
    type: Literal['integer', 'string', 'number', 'boolean', 'array', 'record']
    bit_mask: int | None = Field(default=None, ge=1)
    nullable: bool = False
    when: dict[str, list[str | int]] = Field(default_factory=dict)
    method: Literal['getFlag', 'getMonthlyExpenditure'] | None = None
    method_arg_arg: str | None = None
    fields: list['Observation'] | None = None
    item_type: Literal['integer', 'string'] | None = None
    nullable_items: bool = False
    offset_arg: str | None = None
    limit_arg: str | None = None
    method_arg: str | None = None
    index_arg: str | None = None
    member: str | None = None


class Readback(Definition):
    fields: list[Observation] = Field(min_length=1)
    matches: dict[str, str] = Field(default_factory=dict)


class Operation(Definition):
    name: str
    endpoint: str
    action: str | None = None
    source: Literal['ride', 'objects', 'entity', 'entities', 'park', 'research', 'date', 'climate', 'scenario', 'context', 'object', 'object_manager', 'tile'] | None = None
    identity: str | None = None
    target: Literal['ride', 'entity', 'park', 'research', 'date', 'context'] | None = None
    entity_type: str | None = None
    object_type: str | None = None
    object_type_arg: str | None = None
    entity_type_arg: str | None = None
    description: str = Field(min_length=1)
    arguments: list[Argument] = Field(default_factory=list)
    constants: dict[str, int | str | bool] = Field(default_factory=dict)
    response: Literal['message', 'acknowledgement', 'payload', 'readback', 'observation']
    success_message: str | None = None
    error_prefix: str
    destructive: bool = True
    allowed_modes: list[Literal['normal', 'scenario_editor', 'track_designer', 'track_manager', 'title']] = Field(default_factory=lambda: ['normal'], min_length=1)
    readback: Readback | None = None
    result_fields: list[Observation] = Field(default_factory=list)
    required_objects: dict[str, str] = Field(default_factory=dict)


class Registry(Definition):
    engine_version: Literal['0.5.7']
    operations: list[Operation] = Field(min_length=1)


def load_registry(path: Path = PACKAGE / 'actions.json') -> Registry:
    registry = Registry.model_validate(json.loads(path.read_text()))
    names, endpoints = set(), set()
    for op in registry.operations:
        if op.name in names or op.endpoint in endpoints:
            raise ValueError('Operation names and endpoints must be unique')
        names.add(op.name)
        endpoints.add(op.endpoint)
        for name in [op.name, op.endpoint, *([op.action] if op.action else []), *op.constants,
                     *(arg.name for arg in op.arguments), *(arg.wire_name for arg in op.arguments),
                     *(arg.action_field for arg in op.arguments)]:
            if not name.isidentifier() or keyword.iskeyword(name):
                raise ValueError(f'Invalid identifier: {name}')
        arguments = {arg.name for arg in op.arguments}
        wire_names = {arg.wire_name for arg in op.arguments}
        action_fields = {arg.action_field for arg in op.arguments}
        if 'flags' in action_fields or 'flags' in op.constants:
            raise ValueError('Global GameAction flags are not a public registry argument')
        if (len(arguments) != len(op.arguments) or len(wire_names) != len(op.arguments) or
                len(action_fields) != len(op.arguments) or action_fields & op.constants.keys()):
            raise ValueError('Argument names/mappings must be unique and not overwrite constants')
        observation = op.response == 'observation'
        if op.identity is None:
            op.identity = next((arg.name for arg in op.arguments if arg.name in {
                'ride_id', 'entity_id', 'staff_id', 'guest_id', 'banner_id',
            }), None)
        if op.identity is not None and op.identity not in arguments:
            raise ValueError('Identity must reference an argument')
        if observation:
            if op.action or op.constants or not op.source:
                raise ValueError('Observations require a fixed source, not an engine action')
        elif not op.action or op.source:
            raise ValueError('Mutations require a fixed engine action, not an observation source')
        if op.source in {'objects', 'object'} and bool(op.object_type) == bool(op.object_type_arg):
            raise ValueError('Object observations need exactly one fixed or enum-selected object type')
        if not set(op.required_objects) <= arguments:
            raise ValueError('Loaded-object requirements must reference arguments')
        for selector in (op.object_type_arg, op.entity_type_arg):
            if selector and (selector not in arguments or not next(a for a in op.arguments if a.name == selector).values):
                raise ValueError('Type selectors must reference declared enums')
        if (op.source in {'ride', 'entity'} or op.target in {'ride', 'entity'}) and op.identity is None:
            raise ValueError('Entity/ride targets require an identity argument')
        if (op.source == 'ride' or op.target == 'ride' or
                (not observation and op.readback is not None and op.target is None)) and op.identity != 'ride_id':
            raise ValueError('Ride readback requires ride_id')
        if op.source == 'entities' and 'limit' not in arguments:
            raise ValueError('Entity lists must be bounded')
        for arg in op.arguments:
            if arg.boolean_as_integer and arg.type != 'boolean':
                raise ValueError('Boolean conversion requires a boolean argument')
            if arg.values is not None and (arg.type != 'string' or not arg.values):
                raise ValueError('Only nonempty string enums can map to action values')
            if arg.type != 'integer' and (arg.minimum is not None or arg.maximum is not None or arg.multiple_of is not None):
                raise ValueError('Non-integer arguments cannot have integer bounds')
            if arg.type != 'string' and arg.min_length is not None:
                raise ValueError('Non-string arguments cannot have a string length')
            if arg.minimum is not None and arg.maximum is not None and arg.minimum > arg.maximum:
                raise ValueError('Invalid integer bounds')
        if (op.response == 'message') != (op.success_message is not None):
            raise ValueError('Message responses require a success message, exclusively')
        if (op.response in {'readback', 'observation'}) != (op.readback is not None):
            raise ValueError('Readback responses require observations, exclusively')
        if op.readback:
            fields = {field.name for field in op.readback.fields}
            if (len(fields) != len(op.readback.fields) or (not observation and not op.readback.matches) or
                    not op.readback.matches.keys() <= fields or not set(op.readback.matches.values()) <= arguments):
                raise ValueError('Readback matches must reference declared fields and arguments')
            if observation and op.readback.matches:
                raise ValueError('Observations cannot match mutation arguments')
        validate_fields([*(op.readback.fields if op.readback else []), *op.result_fields], op)
    return registry


def validate_fields(fields: list[Observation], op: Operation) -> None:
    arguments = {arg.name: arg for arg in op.arguments}
    names = []
    for field in fields:
        if not field.name.isidentifier() or not re.fullmatch(r'[A-Za-z]\w*(?:\.[A-Za-z]\w*)*', field.property):
            raise ValueError('Projection fields need identifiers and fixed property paths')
        if field.when and (not field.nullable or any(not key.isidentifier() or not values for key, values in field.when.items())):
            raise ValueError('Conditional fields need fixed nonempty conditions and nullable output')
        names.append(field.name)
        if field.type == 'array':
            names.append(field.name + '_total')
            if bool(field.fields) == bool(field.item_type):
                raise ValueError('Arrays require either record fields or a scalar item type')
        elif field.item_type or field.nullable_items or field.offset_arg or field.limit_arg:
            raise ValueError('Array options require an array projection')
        if (field.type == 'record') != bool(field.fields) and field.type != 'array':
            raise ValueError('Records require nested fields, exclusively')
        if field.bit_mask is not None and field.type != 'boolean':
            raise ValueError('Bit masks require boolean observations')
        for selector in (field.index_arg, field.offset_arg, field.limit_arg):
            if selector:
                arg = arguments.get(selector)
                if not arg or arg.type != 'integer' or arg.minimum is None or arg.minimum < 0:
                    raise ValueError('Projection selectors require bounded nonnegative integer arguments')
                if selector == field.limit_arg and (arg.maximum is None or arg.maximum > 256):
                    raise ValueError('Array page size cannot exceed 256')
        if bool(field.offset_arg) != bool(field.limit_arg):
            raise ValueError('Paged arrays require offset and limit together')
        if field.method:
            if field.method != field.property or bool(field.method_arg) == bool(field.method_arg_arg):
                raise ValueError('Methods require a fixed reviewed name and exactly one argument')
            if field.method_arg_arg and (field.method_arg_arg not in arguments or not arguments[field.method_arg_arg].values):
                raise ValueError('Method argument selectors require a declared enum')
        elif field.method_arg or field.method_arg_arg:
            raise ValueError('Method arguments require a reviewed method')
        if field.fields:
            validate_fields(field.fields, op)
    if len(names) != len(set(names)):
        raise ValueError('Projection names and array total names must be unique')


def annotation(arg: Argument, *, constrained: bool) -> str:
    if arg.values:
        return 'Literal[' + ', '.join(repr(value) for value in arg.values) + ']'
    result = {'integer': 'int', 'string': 'str', 'boolean': 'bool'}[arg.type]
    constraints = ['strict=True'] + [f'{key}={value}' for key, value in (
        ('ge', arg.minimum), ('le', arg.maximum), ('min_length', arg.min_length), ('multiple_of', arg.multiple_of),
    ) if value is not None]
    return f'Annotated[{result}, Field({", ".join(constraints)})]' if constrained and constraints else result


def client_source(registry: Registry) -> str:
    # Sort explicitly so generated output is deterministic across processes.
    reads = 'frozenset(' + repr(sorted(op.endpoint for op in registry.operations if op.response == 'observation')) + ')'
    names = 'frozenset(' + repr(sorted(op.name for op in registry.operations)) + ')'
    lines = [HEADER, f'from typing import Any, Literal\n\nREAD_ENDPOINTS = {reads}\nGENERATED_TOOL_NAMES = {names}\n\n\nclass ActionClient:\n']
    for op in registry.operations:
        args = ''.join(f', {arg.name}: {annotation(arg, constrained=False)}' for arg in op.arguments)
        params = '{' + ', '.join(f'{arg.wire_name!r}: {arg.name}' for arg in op.arguments) + '}'
        lines.append(f'    def {op.name}(self{args}) -> Any:\n'
                     f'        return self._send_action({op.endpoint!r}, {params},\n'
                     f'                                 expect_object={op.response != "message"})\n\n')
    return ''.join(lines)


def tools_source(registry: Registry) -> str:
    lines = [HEADER, '''from typing import Annotated, Any, Callable, Literal

from fastmcp import FastMCP
from pydantic import Field

from .api_client import APIError, OpenRCT2API
from .results import action_result, mutation_failure


def register_action_tools(mcp: FastMCP, get_api: Callable[[], OpenRCT2API]) -> dict[str, Callable]:
''']
    for op in registry.operations:
        args = ', '.join(f'{arg.name}: {annotation(arg, constrained=True)}' for arg in op.arguments)
        values = ', '.join(arg.name for arg in op.arguments)
        observation = op.response == 'observation'
        identity = op.identity or 'None'
        success = ("{'success': True, **payload}" if observation else
                   f"action_result({identity}, payload, {op.response!r}, identity_key={op.identity!r})")
        failure = (f"{{'success': False, 'error': str(error)" +
                   (f", {op.identity!r}: {op.identity}}}" if op.identity else '}') if observation else
                   f'mutation_failure(error, identity={identity}, identity_key={op.identity!r})')
        lines.append(f"    @mcp.tool(annotations={{'readOnlyHint': {observation}, 'openWorldHint': False, "
                     f"'destructiveHint': {False if observation else op.destructive}, 'idempotentHint': {observation}}})\n"
                     f'    def {op.name}({args}) -> dict[str, Any]:\n'
                     f'        {op.description!r}\n'
                     f'        try:\n'
                     f'            payload = get_api().{op.name}({values})\n'
                     f'            return {success}\n'
                     f'        except APIError as error:\n'
                     f'            return {failure}\n\n')
    lines.append('    return {\n' + ''.join(f'        {op.name!r}: {op.name},\n' for op in registry.operations) + '    }\n')
    return ''.join(lines)


def plugin_source(registry: Registry) -> str:
    table = {op.endpoint: op.model_dump(exclude={'description', 'destructive', 'endpoint'}, exclude_none=True, exclude_defaults=True)
             for op in registry.operations}
    surface = json.loads((ROOT / 'docs/game-api-surface.json').read_text())
    build_types = surface['ride_build_types']
    build_table = {str(entry['ride_type']): entry for entry in build_types}
    flags = json.dumps(surface['ride_entry_flags'], sort_keys=True)
    return START + '    var rideEntryFlags = ' + flags + ';\n    var rideBuildTypes = ' + json.dumps(build_table, sort_keys=True) + ';\n' + '    var registeredActions = ' + json.dumps(table, indent=4).replace('\n', '\n    ') + ';\n' + END


def inventory_source(descriptions: dict[str, str]) -> str:
    rows = []
    for name, description in sorted(descriptions.items()):
        summary = ' '.join(description.split()).partition('. ')[0].rstrip('.') + '.'
        rows.append(f'- `{name}` — {summary}\n')
    return ''.join(rows)


def generate(check: bool = False) -> bool:
    registry = load_registry()
    plugin = ROOT / 'openrct2-mcp.js'
    text = plugin.read_text()
    before, tail = text.split(START, 1)
    _, after = tail.split(END, 1)
    readme = ROOT / 'README.md'
    prefix, inventory = readme.read_text().split('<!-- BEGIN GENERATED TOOL INVENTORY -->\n', 1)
    _, suffix = inventory.split('<!-- END GENERATED TOOL INVENTORY -->', 1)
    descriptions = json.loads((ROOT / 'docs/custom-tools.json').read_text())
    if descriptions.keys() & {op.name for op in registry.operations}:
        raise ValueError('Custom and generated tool names must not overlap')
    descriptions.update({op.name: op.description for op in registry.operations})
    table = inventory_source(descriptions)
    outputs = {
        readme: prefix + '<!-- BEGIN GENERATED TOOL INVENTORY -->\n' + table + '<!-- END GENERATED TOOL INVENTORY -->' + suffix,
        PACKAGE / '_action_client.py': client_source(registry),
        PACKAGE / '_action_tools.py': tools_source(registry),
        plugin: before + plugin_source(registry) + after,
    }
    stale = []
    audit = subprocess.run([sys.executable, str(ROOT / 'scripts/audit_game_api.py'), *(['--check'] if check else [])])
    if audit.returncode:
        if not check:
            raise RuntimeError('API coverage validation failed')
        stale.append('docs/api-coverage.md')
    for path, content in outputs.items():
        if not path.exists() or path.read_text() != content:
            stale.append(str(path.relative_to(ROOT)))
            if not check:
                path.write_text(content)
    if stale:
        print(('Stale: ' if check else 'Generated: ') + ', '.join(stale))
    return not (check and stale)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail on stale generated files without writing')
    raise SystemExit(0 if generate(parser.parse_args().check) else 1)
